#!/usr/bin/env node
// Writes src/tools/resold-specs.generated.ts from Runway's published API spec
// (https://docs.dev.runwayml.com/openapi.json): for each model Runway resells
// from another maker, the fields it accepts and their limits. Prices, labels and
// defaults are not in the spec; they stay by hand in resold-models.ts.
//
//   curl -sSf https://docs.dev.runwayml.com/openapi.json -o /some/dir/openapi.json
//   node scripts/generate-resold-specs.mjs /some/dir/openapi.json          (write)
//   node scripts/generate-resold-specs.mjs /some/dir/openapi.json --check  (compare)
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

export const MODELS = {
  '/v1/image_to_video': ['kling_4', 'kling_4_flash', 'seedance2_5', 'seedance2_5_flash', 'gemini_omni_flash_1.2', 'hailuo3', 'h3_max', 'wan3', 'wan3_prime', 'grok_imagine_1_5', 'grok_imagine_1_5_lite', 'happyhorse_1_0'],
  '/v1/text_to_video': ['kling_4', 'kling_4_flash', 'seedance2_5', 'seedance2_5_flash', 'gemini_omni_flash_1.2', 'hailuo3', 'h3_max', 'wan3', 'wan3_prime', 'grok_imagine_1_5', 'grok_imagine_1_5_lite', 'happyhorse_1_0'],
  '/v1/text_to_image': ['gemini_image3_pro', 'gpt_image_2_6_sunburst', 'gpt_image_2_6_flare', 'gemini_image3.1_flash', 'gemini_image3.1_flash_lite', 'nano_banana_2.1', 'seedream5.5', 'minimax_h3_image', 'ideogram_4_5', 'grok_imagine_image_2', 'muse_image', 'bria_fibo_1_5'],
};

const variantsOf = (schema) => schema.oneOf ?? schema.anyOf ?? [schema];
const branches = (p) => (p ? [p, ...(p.anyOf ?? p.oneOf ?? []).flatMap(branches)] : []);
const find = (p, test) => branches(p).find(test);

function describe(variant) {
  const props = variant.properties ?? {};
  const required = variant.required ?? [];
  const prompt = props.promptText ?? {};
  const out = {
    fields: Object.keys(props).filter((k) => k !== 'model').sort(),
    promptRequired: required.includes('promptText'),
    minPrompt: prompt.minLength ?? 1,
    maxPrompt: prompt.maxLength ?? null,
    ratios: find(props.ratio, (b) => b.enum)?.enum ?? (find(props.ratio, (b) => b.const) ? [find(props.ratio, (b) => b.const).const] : []),
    resolutions: [...new Set((find(props.resolution, (b) => b.enum)?.enum ?? []).map((r) => r.toLowerCase()))],
  };
  const duration = find(props.duration, (b) => b.type === 'integer' || b.type === 'number');
  if (duration) out.duration = { min: duration.minimum, max: duration.maximum };
  const seed = find(props.seed, (b) => b.maximum !== undefined);
  if (seed) out.seedMax = seed.maximum;
  const frames = find(props.promptImage, (b) => b.type === 'array');
  // Some models' frame items carry no schema, only prose ("an optional last frame"), so the prose counts too.
  if (props.promptImage) out.lastFrame = !!frames && /\blast\b/.test(JSON.stringify(props.promptImage));
  const refs = find(props.referenceImages, (b) => b.type === 'array');
  if (refs) {
    out.maxReferences = refs.maxItems;
    out.referenceTags = !!refs.items?.properties?.tag;
  }
  return out;
}

export function generate(spec) {
  const root = Array.isArray(spec) ? spec[0].spec.default : spec;
  const tables = {};
  for (const [path, models] of Object.entries(MODELS)) {
    const variants = variantsOf(root.paths[path].post.requestBody.content['application/json'].schema);
    tables[path] = {};
    for (const model of models) {
      const variant = variants.find((v) => v.properties?.model?.const === model);
      if (!variant) throw new Error(`${model} is not in ${path} of this spec.`);
      tables[path][model] = describe(variant);
    }
  }
  return tables;
}

function render(tables, source) {
  const name = { '/v1/image_to_video': 'IMAGE_TO_VIDEO', '/v1/text_to_video': 'TEXT_TO_VIDEO', '/v1/text_to_image': 'TEXT_TO_IMAGE' };
  const lines = [
    '// Generated by scripts/generate-resold-specs.mjs from Runway\'s published API spec. Do not edit by hand.',
    `// Source: https://docs.dev.runwayml.com/openapi.json, version ${source.version}, sha256 ${source.sha256}.`,
    '// The models were read from the documentation, never called (FOX-12868).',
    '',
    'export interface ResoldFieldSpec {',
    '  /** Request fields the model accepts, besides model. Anything else is refused by Runway. */',
    '  fields: readonly string[];',
    '  promptRequired: boolean;',
    '  minPrompt: number;',
    '  maxPrompt: number | null;',
    '  /** Allowed ratios; empty when the model takes no ratio here. */',
    '  ratios: readonly string[];',
    '  /** Allowed resolutions, lowercased; empty when the model takes none. */',
    '  resolutions: readonly string[];',
    '  duration?: { min: number; max: number };',
    '  seedMax?: number;',
    '  /** Image-to-video: whether promptImage may carry a last frame as well as the first. */',
    '  lastFrame?: boolean;',
    '  maxReferences?: number;',
    '  referenceTags?: boolean;',
    '}',
    '',
  ];
  for (const [path, models] of Object.entries(tables)) {
    lines.push(`export const ${name[path]}: Record<string, ResoldFieldSpec> = {`);
    for (const [model, spec] of Object.entries(models)) lines.push(`  ${JSON.stringify(model)}: ${JSON.stringify(spec)},`);
    lines.push('};', '');
  }
  return lines.join('\n');
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const [input, flag] = process.argv.slice(2);
  if (!input) {
    console.error('Usage: node scripts/generate-resold-specs.mjs <openapi.json> [--check]');
    process.exit(2);
  }
  const bytes = readFileSync(input);
  const spec = JSON.parse(bytes.toString('utf8'));
  const root = Array.isArray(spec) ? spec[0].spec.default : spec;
  const text = render(generate(spec), { version: root.info?.version ?? 'unknown', sha256: createHash('sha256').update(bytes).digest('hex') });
  const target = resolve(dirname(fileURLToPath(import.meta.url)), '../src/tools/resold-specs.generated.ts');
  if (flag === '--check') {
    if (readFileSync(target, 'utf8') !== text) {
      console.error('src/tools/resold-specs.generated.ts differs from this spec; rerun without --check.');
      process.exit(1);
    }
    console.log('resold-specs.generated.ts matches the spec.');
  } else {
    writeFileSync(target, text);
    console.log(`Wrote ${target}`);
  }
}
