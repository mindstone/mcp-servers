// Generates src/resources/compose-email-template.ts (and its compose-email.html
// preview twin) from the shared @mindstone/mcp-app-compose builder.
//
// Usage:
//   node scripts/gen-compose-html.mjs           regenerate both files
//   node scripts/gen-compose-html.mjs --check   verify committed files match (used by pretest)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildComposeAppHtml } from '@mindstone/mcp-app-compose/template';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const templatePath = path.join(root, 'src/resources/compose-email-template.ts');
const previewPath = path.join(root, 'src/resources/compose-email.html');

/**
 * Outlook's configuration of the shared compose app. This is the single source
 * of truth for the connector-specific knobs; the parity test asserts that
 * building with it reproduces the committed template byte-for-byte.
 *
 * deepLink is 'none' because the Graph sendMail endpoint returns no message id
 * to link to.
 */
export const OUTLOOK_COMPOSE_APP_CONFIG = Object.freeze({
  resourceUri: 'ui://microsoft-mail/compose-email',
  sendToolName: 'send_email',
  // Save-draft button: persists the composed email to Outlook Drafts via the
  // connector's existing create_draft tool instead of sending.
  draftToolName: 'create_draft',
  fromMissingHelperText:
    'Rebel could not confirm the sending account. Cancel and ask Rebel to recreate the draft before sending.',
  fields: Object.freeze({ cc: true, bcc: true }),
  deepLink: Object.freeze({ kind: 'none' }),
});

const HEADER = [
  '// GENERATED by scripts/gen-compose-html.mjs — do not edit by hand.',
  '// Regenerate with "npm run compose:template"; "npm test" runs the --check drift gate.',
  '// The generator also writes compose-email.html, keeping the two in sync.',
].join('\n');

function escapeForTemplateLiteral(html) {
  return html.replaceAll('\\', '\\\\').replaceAll('`', '\\`').replaceAll('${', '\\${');
}

export function buildFileContents() {
  const html = buildComposeAppHtml(OUTLOOK_COMPOSE_APP_CONFIG);
  const templateTs = `${HEADER}\nexport const COMPOSE_EMAIL_HTML = \`${escapeForTemplateLiteral(html)}\`;\n`;
  // The runtime string starts with "\n" so the template literal opens cleanly;
  // the standalone preview drops that leading newline.
  const previewHtml = html.slice(1);
  return { templateTs, previewHtml };
}

function main() {
  const check = process.argv.includes('--check');
  const { templateTs, previewHtml } = buildFileContents();

  if (check) {
    const stale = [];
    for (const [file, expected] of [
      [templatePath, templateTs],
      [previewPath, previewHtml],
    ]) {
      const actual = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null;
      if (actual !== expected) stale.push(path.relative(root, file));
    }
    if (stale.length > 0) {
      process.stderr.write(
        `${stale.join(', ')} out of sync with @mindstone/mcp-app-compose. Run "npm run compose:template" and commit the result.\n`,
      );
      process.exit(1);
    }
    console.log('compose-email template is up to date');
    return;
  }

  fs.writeFileSync(templatePath, templateTs);
  fs.writeFileSync(previewPath, previewHtml);
  console.log(`wrote ${path.relative(root, templatePath)} and ${path.relative(root, previewPath)}`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main();
}
