          // BCP-47-shaped: satisfies any /^[a-z]{2,3}(-[a-zA-Z0-9]{2,8})*$/
          // style grammar gate, yet is instruction-shaped. Grammar-gating is
          // therefore not a trust boundary here — the value must be enveloped.
