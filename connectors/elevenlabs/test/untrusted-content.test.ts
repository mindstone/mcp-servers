describe('tool sources reach the envelope helper (mechanical guard on the source)', () => {
  it('every tool file returning external text imports and calls wrapUntrusted', async () => {
    const nodeFs = await import('node:fs');
    const nodePath = await import('node:path');
    const nodeUrl = await import('node:url');
    const dir = nodePath.dirname(nodeUrl.fileURLToPath(import.meta.url));
    // voices (name/description/labels), account (model names), transcription
    // (transcript text), speech (API-resolved voice name), alignment (word text),
    // dubbing (job name + error detail) all return external text.
    const TOOLS = ['voices.ts', 'account.ts', 'transcription.ts', 'speech.ts', 'alignment.ts', 'dubbing.ts'];

    for (const f of TOOLS) {
      const contents = nodeFs.readFileSync(nodePath.join(dir, '..', 'src', 'tools', f), 'utf-8');
      expect(
        contents,
        `${f} must import from ../untrusted-content.js (AGENTS.md invariant #6)`,
      ).toContain("from '../untrusted-content.js'");
      expect(
        contents,
        `${f} must call wrapUntrusted* at every external-text field`,
      ).toMatch(/wrapUntrusted\w*\(/);
    }
  });

  it('error-detail helper imports wrapUntrusted for API error paths', async () => {
    const nodeFs = await import('node:fs');
    const nodePath = await import('node:path');
    const nodeUrl = await import('node:url');
    const dir = nodePath.dirname(nodeUrl.fileURLToPath(import.meta.url));
    const contents = nodeFs.readFileSync(
      nodePath.join(dir, '..', 'src', 'error-detail.ts'),
      'utf-8',
    );
    expect(contents).toContain("from './untrusted-content.js'");
    expect(contents).toMatch(/wrapUntrusted\(/);
  });
});
