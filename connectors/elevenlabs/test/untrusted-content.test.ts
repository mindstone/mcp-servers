/**
 * `<untrusted-content>` envelope discipline per AGENTS.md invariant #6
 * (FOX-3490 remediation — this connector was baselined as a known P1 gap:
 * "voice names/descriptions + transcribed audio text").
 *
 * External-text surface of this connector:
 *   - list_voices / get_voice / search_shared_voices: voice `name` / `description` /
 *     `labels` / accent / descriptive / use_case — authored by voice creators.
 *   - list_models: model and language `name` fields from the API catalogue.
 *   - transcribe_audio: `text` — whatever was SPOKEN in the audio — plus the
 *     API-detected `language_code` (API-authored; grammar-gating it is not a
 *     trust boundary).
 *   - generate_speech: the API-resolved voice `name` echoed back.
 *   - client error paths: API `detail` strings in ElevenLabsError messages.
 *   - get_dubbing: job `name` and error detail strings (user-supplied name echoed via API).
 *
 * create_music_plan's composition plan is generated by the ElevenLabs model and
 * returned with free-text fields enveloped; generate_music_from_plan unwraps
 * those fields before strict validation and API submission.
 *
 * These tests assert (a) the vendored wrapper is correct, (b) it defangs
 * close-tag breakouts, (c) each end-to-end tool path actually reaches it, and
 * (d) — the mechanical reachability guard — fixture-sourced external strings
 * appear in tool output ONLY inside envelopes, so "no unwrapped API-authored
 * substrings in `message`" is enforced, not just stated.
 */
